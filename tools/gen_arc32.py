#!/usr/bin/env python3
"""Generate ARC32_ops.sinc: the ALU, single-operand, branch/jump/loop and load/store constructors
of the legacy ARC (ARC32) SLEIGH specification.

  tools/gen_arc32.py <out.sinc>        (the checked-in file is data/languages/ARC32_ops.sinc)

Every instruction gets separate constructors for its unconditional and conditional forms (and,
for ALU operations, for its flag-setting and non-flag-setting forms; for loads and stores, per
access size), so that the p-code has no branches on values that are constant for an encoding.
Such branches make an unconditional jump look as if it could fall through, and they stop
constant propagation (e.g. "mov r4,limm" would leave r4 unknown).

Encodings and semantics: ARCtangent-A4 Programmer's Reference (ARC International, 2002).
"""
import sys

out = []
A = out.append

# Constraint fragments
NSB = "(Bb5=0 | (Bb5=1 & Bb4=0) | (Bb5=1 & Bb4=1 & Bb3=0) | Bt=14 | (Bt=15 & Bb0=0))"             # B is not a short-immediate indicator
NSC = "(Cb5=0 | (Cb5=1 & Cb4=0) | (Cb5=1 & Cb4=1 & Cb3=0) | Ct=14 | (Ct=15 & Cb0=0))"            # C is not a short-immediate indicator
# Dual-operand forms: unconditional (short immediate somewhere, or Q=0) / conditional, and the
# flag-setting rule (C decides when it holds a short immediate, then B, otherwise the F bit)
DUAL = {
    ("u", 1): f"(Cr=61 | (Br=61 & {NSC}) | ({NSB} & {NSC} & Q=0 & F=1))",
    ("u", 0): f"(Cr=63 | (Br=63 & {NSC}) | ({NSB} & {NSC} & Q=0 & F=0))",
    ("c", 1): f"{NSB} & {NSC} & F=1 & Qcc",
    ("c", 0): f"{NSB} & {NSC} & F=0 & Qcc",
}
SINGLE = {
    ("u", 1): f"(Br=61 | ({NSB} & Q=0 & F=1))",
    ("u", 0): f"(Br=63 | ({NSB} & Q=0 & F=0))",
    ("c", 1): f"{NSB} & F=1 & Qcc",
    ("c", 0): f"{NSB} & F=0 & Qcc",
}

# Dual-operand operations: (mnemonic or name subtable, major, flag kind, result/flag code).
# The code sees a and b (operands 1 and 2) and computes r; FLAGS is replaced by the flag code.
LOGIC = "zn(r);"
DUAL_OPS = [
    ("addm", 0x08, "r = a + b;", "addflags(a, b, r);"),
    ("adcm", 0x09, "local cin:4 = zext(C); local t:4 = a + b; r = t + cin;",
     "zn(r); C = carry(a, b) || carry(t, cin); V = ((a ^ r) & (b ^ r)) s< 0;"),
    ("sub", 0x0a, "r = a - b;", "subflags(a, b, r);"),
    ("sbc", 0x0b, "local cin:4 = zext(C); local t:4 = a - b; r = t - cin;",
     "zn(r); C = (a < b) || (t < cin); V = ((a ^ b) & (a ^ r)) s< 0;"),
    ("andm", 0x0c, "r = a & b;", LOGIC),
    ("or", 0x0d, "r = a | b;", LOGIC),
    ("bic", 0x0e, "r = a & ~b;", LOGIC),
    ("xor", 0x0f, "r = a ^ b;", LOGIC),
    # optional barrel shifter: shift by the low five bits of operand 2; Z and N only
    ("asl", 0x10, "r = a << (b & 31);", LOGIC),
    ("lsr", 0x11, "r = a >> (b & 31);", LOGIC),
    ("asr", 0x12, "r = a s>> (b & 31);", LOGIC),
    ("ror", 0x13, "local n:4 = b & 31; r = (a >> n) | (a << ((32 - n) & 31));", LOGIC),
    # optional MIN/MAX: flags as for SUB a,b; C set when operand 2 is selected
    ("max", 0x1e, "local sel:1 = (b s>= a); r = (zext(sel) * b) + (zext(!sel) * a);",
     "local d:4 = a - b; zn(d); V = sborrow(a, b); C = sel;"),
    ("min", 0x1f, "local sel:1 = (b s<= a); r = (zext(sel) * b) + (zext(!sel) * a);",
     "local d:4 = a - b; zn(d); V = sborrow(a, b); C = sel;"),
]


def mn(name):
    """Mnemonic text: a name subtable (addm/adcm/andm: asl/rlc/mov when B = C) or a literal."""
    return "^" + name if name.endswith("m") and name in ("addm", "adcm", "andm") else name


def ops_text(name):
    return "dst, srcB^opc" if name in ("addm", "adcm", "andm") else "dst, srcB, srcC"


def dual(name, major, code, flags, extra_pat="", extra_disp=""):
    for (form, f), pat in DUAL.items():
        cc = "^\".\"^Qcc" if form == "c" else ""
        fd = "^\".f\"" if f else ""
        opsx = " & opc ..." if name in ("addm", "adcm", "andm") else ""
        npat = f" & {name}" if name in ("addm", "adcm", "andm") else ""
        A(f":{mn(name)}{extra_disp}{cc}{fd}^ndx {ops_text(name)} is (I={major:#04x}{npat}{extra_pat} & dst & ndx & {pat})"
          f" ... & srcB ... & srcC ...{opsx} {{")
        if form == "c":
            A("\tif (!Qcc) goto <skip>;")
        A(f"\tlocal a:4 = srcB; local b:4 = srcC; local r:4;\n\t{code}")
        if f:
            A(f"\t{flags}")
        A("\tdst = r;")
        if form == "c":
            A("<skip>")
        A("}")


def k_pat_of(kname, kpat):
    """The flag constraint a jump kind carries itself (j.f [ilink] is the only F=1-only kind)."""
    return "F=1" if kpat.endswith("& F=1") else ""


def generate():
    A("# Generated by tools/gen_arc32.py; do not edit (edit the generator and rerun it).")
    A("")
    A("# ---------------------------------------------------------------------------------------------")
    A("# Dual-operand instructions: op<.cc><.f> a,b,c (majors 0x08-0x0f and the 0x10-0x1f options).")
    A("# Short-immediate forms cannot be conditional (D overlays Q, F and N).")
    A("")
    for name, major, code, flags in DUAL_OPS:
        dual(name, major, code, flags)
        A("")
    # multiplier: no flags; ".f" is shown as objdump does
    A("# Optional 32x32 multiplier (0x14 signed, 0x15 unsigned): MLO (r57), MMID (r58), MHI (r59);")
    A("# flags are not affected. The destination field holds an immediate indicator.")
    for name, major, ext in (("mul64", 0x14, "sext"), ("mulu64", 0x15, "zext")):
        for (form, f), pat in DUAL.items():
            cc = "^\".\"^Qcc" if form == "c" else ""
            fd = "^\".f\"" if f else ""
            A(f":{name}{cc}{fd}^ndx dst, srcB, srcC is (I={major:#04x} & dst & ndx & {pat}) ... & srcB ... & srcC ... {{")
            if form == "c":
                A("\tif (!Qcc) goto <skip>;")
            A(f"\tlocal p:8 = {ext}(srcB) * {ext}(srcC);\n\tr57 = p:4; r58 = p(2); r59 = p(4);")
            if form == "c":
                A("<skip>")
            A("}")
    A("")
    A("# User extension instructions (majors 0x16-0x1d): operation defined by the core")
    for (form, f), pat in DUAL.items():
        cc = "^\".\"^Qcc" if form == "c" else ""
        fd = "^\".f\"" if f else ""
        A(f":^extmaj{cc}{fd}^ndx dst, srcB, srcC is (I>=0x16 & I<=0x1d & extmaj & dst & ndx & {pat}) ... & srcB ... & srcC ... {{")
        if form == "c":
            A("\tif (!Qcc) goto <skip>;")
        A(f"\tdst = ext_instruction(extmaj, srcB, srcC, {f}:1);")
        if form == "c":
            A("<skip>")
        A("}")
    A("")

    # ---------------------------------------------------------------- single operand
    A("# ---------------------------------------------------------------------------------------------")
    A("# Single-operand instructions (major 0x03, sub-opcode in C): op<.cc><.f> a,b")
    A("")
    SOPS = [
        ("asr", 0x01, "r = a s>> 1;", "zn(r); C = (a & 1) != 0;"),
        ("lsr", 0x02, "r = a >> 1;", "zn(r); C = (a & 1) != 0;"),
        ("ror", 0x03, "r = (a >> 1) | (a << 31);", "zn(r); C = (a & 1) != 0;"),
        ("rrc", 0x04, "r = (a >> 1) | (zext(C) << 31);", "zn(r); C = (a & 1) != 0;"),
        ("sexb", 0x05, "r = sext(a:1);", LOGIC),
        ("sexw", 0x06, "r = sext(a:2);", LOGIC),
        ("extb", 0x07, "r = zext(a:1);", LOGIC),
        ("extw", 0x08, "r = zext(a:2);", LOGIC),
        # optional SWAP and NORM; NORM: number of redundant sign bits (31 for 0 and -1)
        ("swap", 0x09, "r = (a << 16) | (a >> 16);", LOGIC),
        ("norm", 0x0a, "local x:4 = a ^ (a s>> 31); r = lzcount(x) - 1;", LOGIC),
    ]
    for name, sub, code, flags in SOPS:
        for (form, f), pat in SINGLE.items():
            cc = "^\".\"^Qcc" if form == "c" else ""
            fd = "^\".f\"" if f else ""
            A(f":{name}{cc}{fd}^nd1 dst, src1 is (I=0x03 & Cr={sub:#04x} & dst & nd1 & {pat}) ... & src1 ... {{")
            if form == "c":
                A("\tif (!Qcc) goto <skip>;")
            A(f"\tlocal a:4 = src1; local r:4;\n\t{code}")
            if f:
                A(f"\t{flags}")
            A("\tdst = r;")
            if form == "c":
                A("<skip>")
            A("}")
        A("")
    A("# Other single-operand extension sub-opcodes (0x3d and 0x3e are the immediate indicators 61/62")
    A("# and are not decoded)")
    for (form, f), pat in SINGLE.items():
        cc = "^\".\"^Qcc" if form == "c" else ""
        fd = "^\".f\"" if f else ""
        A(f":^Csub{cc}{fd}^nd1 dst, src1 is (I=0x03 & Cr>=0x0b & Cr<=0x3c & Csub & dst & nd1 & {pat}) ... & src1 ... {{")
        if form == "c":
            A("\tif (!Qcc) goto <skip>;")
        A(f"\tdst = ext_instruction(0x03:1, Csub:1, src1, {f}:1);")
        if form == "c":
            A("<skip>")
        A("}")
    A("")
    A("# FLAG (sub-opcode 0): Z N C V E2 E1 H from bits 6..0; when H is set the other flags are kept.")
    A("# The destination field holds an immediate indicator; objdump ignores it and the F bit.")
    for form in ("u", "c"):
        pat = "(Br=61 | Br=63 | (" + NSB + " & Q=0))" if form == "u" else NSB + " & Qcc"
        cc = "^\".\"^Qcc" if form == "c" else ""
        A(f":flag{cc}^nd1 src1 is (I=0x03 & Cr=0x00 & nd1 & {pat}) ... & src1 ... {{")
        if form == "c":
            A("\tif (!Qcc) goto <skip>;")
        A("\tsetflags(src1);")
        if form == "c":
            A("<skip>")
        A("}")
    A("")

    # ---------------------------------------------------------------- branches
    A("""# ---------------------------------------------------------------------------------------------
# Branch, branch and link, loop set-up: op<cc><.dd> rel_addr. The delay-slot mode: ND executes the
# next instruction only when not branching, D always, JD only when branching (a nullified delay
# slot continues after it; BL/JL link to the instruction after the delay slot for D and JD).
""")
    modes = [("ND", "", "(Nul=0 | Nul=3)"), ("D", "^\".d\"", "Nul=1"), ("JD", "^\".jd\"", "Nul=2")]
    for mode, suf, npat in modes:
        for cond in (False, True):
            cc = "^Qcc" if cond else ""
            cpat = "Qcc" if cond else "Q=0"
            extra = " & skipnext" if (mode == "JD" and cond) else ""
            A(f":b{cc}{suf} reltarget is I=0x04 & {cpat} & reltarget & {npat}{extra} {{")
            if not cond:
                if mode != "ND":
                    A("\tdelayslot(1);")
                A("\tgoto reltarget;")
            elif mode == "ND":
                A("\tif (Qcc) goto reltarget;")
            elif mode == "D":
                A("\tlocal c:1 = Qcc;\n\tdelayslot(1);\n\tif (c) goto reltarget;")
            else:
                A("\tif (!Qcc) goto skipnext;\n\tdelayslot(1);\n\tgoto reltarget;")
            A("}")
    A("")
    for mode, suf, npat in modes:
        for cond in (False, True):
            cc = "^Qcc" if cond else ""
            cpat = "Qcc" if cond else "Q=0"
            pre = "" if mode == "ND" else "link2 & "
            extra = " & skipnext" if (mode == "JD" and cond) else ""
            A(f":bl{cc}{suf} reltarget is {pre}I=0x05 & {cpat} & reltarget & {npat}{extra} {{")
            if mode == "ND":
                if cond:
                    A("\tif (!Qcc) goto <skip>;")
                A("\tlocal s:4; getstatus(s, inst_next);\n\tblink = s;\n\tcall reltarget;")
                if cond:
                    A("<skip>")
            elif mode == "D":
                if cond:
                    A("\tlocal c:1 = Qcc;")
                A("\tlocal s:4; getstatus(s, link2);\n\tdelayslot(1);")
                if cond:
                    A("\tif (!c) goto <skip>;")
                A("\tblink = s;\n\tcall reltarget;")
                if cond:
                    A("<skip>")
            else:
                if cond:
                    A("\tif (!Qcc) goto skipnext;")
                A("\tlocal s:4; getstatus(s, link2);\n\tdelayslot(1);\n\tblink = s;\n\tcall reltarget;")
            A("}")
    A("")
    A("# LP: when the condition holds, LP_START = next instruction, LP_END = target (both as PC/4),")
    A("# otherwise branch to the target.")
    for mode, suf, npat in modes:
        for cond in (False, True):
            cc = "^Qcc" if cond else ""
            cpat = "Qcc" if cond else "Q=0"
            extra = " & skipnext" if mode == "JD" else ""
            A(f":lp{cc}{suf} reltarget is I=0x06 & {cpat} & reltarget & {npat}{extra}")
            A("\t[ loopEnd = 1; globalset(reltarget, loopEnd); loopStart = (inst_start + 4) >> 2; globalset(reltarget, loopStart); ] {")
            if not cond:
                if mode == "ND":
                    A("\tlpsetup(&reltarget);")
                elif mode == "D":
                    A("\tdelayslot(1);\n\tlpsetup(&reltarget);")
                else:
                    A("\tlpsetup(&reltarget);\n\tgoto skipnext;")
            elif mode == "ND":
                A("\tif (!Qcc) goto reltarget;\n\tlpsetup(&reltarget);")
            elif mode == "D":
                A("\tlocal c:1 = Qcc;\n\tdelayslot(1);\n\tif (!c) goto reltarget;\n\tlpsetup(&reltarget);")
            else:
                A("\tif (Qcc) goto <setup>;\n\tdelayslot(1);\n\tgoto reltarget;\n<setup>\n\tlpsetup(&reltarget);\n\tgoto skipnext;")
            A("}")
    A("")

    # ---------------------------------------------------------------- jumps
    A("""# ---------------------------------------------------------------------------------------------
# Jump and jump-and-link (major 0x07; bit 9 selects JL): j<cc><.f><.dd> [b] / addr. The target is
# PC[25:2] = bits 23..0 of the operand (STATUS register format); .f loads the flags from
# bits 31..26. j [blink] is a return, j.f [ilink1/ilink2] a return from interrupt.
""")
    kinds = [
        ("j", "cjl=0 & (Br<29 | (Br>31 & (Bb5=0 | (Bb5=1 & Bb4=0) | (Bb5=1 & Bb4=1 & Bb3=0) | Bt=14 | (Bt=15 & Bb1=0 & Bb0=0))) | ((Br=29 | Br=30) & F=0))", "goto [t];", False),
        ("jl", "cjl=1 & (Bb5=0 | (Bb5=1 & Bb4=0) | (Bb5=1 & Bb4=1 & Bb3=0) | Bt=14 | (Bt=15 & Bb1=0 & Bb0=0))", "call [t];", True),
        ("j", "cjl=0 & Br=31", "return [t];", False),
        ("j", "cjl=0 & (Br=29 | Br=30) & F=1", "return [t];", False),
    ]
    for (kname, kpat, act, link), f in [(k, f) for k in kinds for f in (0, 1)]:
        if "F=1" in k_pat_of(kname, kpat) and f == 0:
            continue
        fd = "^\".f\"" if f else ""
        for mode, suf, npat in modes:
            for cond in (False, True):
                cc = "^Qcc" if cond else ""
                cpat = "Qcc" if cond else "Q=0"
                pre = "link2 & " if (link and mode != "ND") else ""
                extra = " & skipnext" if (mode == "JD" and cond) else ""
                linkv = "inst_next" if mode == "ND" else "link2"
                A(f":{kname}{cc}{fd}{suf} jreg is {pre}I=0x07 & {kpat} & jreg & F={f} & {cpat} & {npat}{extra} {{")
                A("\tlocal v:4 = jreg;\n\tlocal t:4 = (v & 0xffffff) << 2;")
                if mode == "ND":
                    if cond:
                        A("\tif (!Qcc) goto <skip>;")
                elif mode == "D":
                    if cond:
                        A("\tlocal c:1 = Qcc;")
                else:
                    if cond:
                        A("\tif (!Qcc) goto skipnext;")
                if link:
                    A(f"\tlocal s:4; getstatus(s, {linkv});")
                if mode != "ND":
                    A("\tdelayslot(1);")
                    if mode == "D" and cond:
                        A("\tif (!c) goto <skip>;")
                if f:
                    A("\tjflags(v);")
                if link:
                    A("\tblink = s;")
                A("\t" + act)
                if cond and mode != "JD":
                    A("<skip>")
                A("}")
        A("")
    A("# j/jl to a long-immediate address (no delay slot: the address occupies it; JL links to the")
    A("# next instruction)")
    for kname, cj, f in [(k, c, f) for k, c in (("j", 0), ("jl", 1)) for f in (0, 1)]:
        fd = "^\".f\"" if f else ""
        for cond in (False, True):
            cc = "^Qcc" if cond else ""
            cpat = "Qcc" if cond else "Q=0"
            A(f":{kname}{cc}{fd}^jnd jlimm is I=0x07 & cjl={cj} & F={f} & jnd & {cpat} & Br=62; jlimm & limm {{")
            if cond:
                A("\tif (!Qcc) goto <skip>;")
            if cj:
                A("\tlocal s:4; getstatus(s, inst_next);")
            if f:
                A("\tjflags(limm:4);")
            if cj:
                A("\tblink = s;\n\tcall jlimm;")
            else:
                A("\tgoto jlimm;")
            if cond:
                A("<skip>")
            A("}")
    A("# j/jl to a short-immediate address (unconditional; .f from the 61 indicator)")
    for kname, cj in (("j", 0), ("jl", 1)):
        for f, b in ((1, 61), (0, 63)):
            fd = "^\".f\"" if f else ""
            A(f":{kname}{fd} jshimm is I=0x07 & cjl={cj} & Br={b} & jshimm & D {{")
            if cj:
                A("\tlocal s:4; getstatus(s, inst_next);")
            if f:
                A("\tlocal v:4 = D; jflags(v);")
            if cj:
                A("\tblink = s;\n\tcall jshimm;")
            else:
                A("\tgoto jshimm;")
            A("}")
    A("")

    # ---------------------------------------------------------------- loads and stores
    A("""# ---------------------------------------------------------------------------------------------
# Loads and stores, one constructor per access size: 0 long word, 1 byte, 2 word (3 is reserved
# and not decoded); .x sign-extends, .a writes the address back to a base register, .di bypasses
# the data cache.
""")
    LOADS = {(0, 0): "*[ram]:4 ea", (0, 1): "*[ram]:4 ea", (1, 0): "zext(*[ram]:1 ea)", (1, 1): "sext(*[ram]:1 ea)",
             (2, 0): "zext(*[ram]:2 ea)", (2, 1): "sext(*[ram]:2 ea)"}
    SZ = {0: '', 1: '"b"', 2: '"w"'}
    for form, fld, addr, fsuf, pfx in (("g", "lg", "lgaddr", "ldfg", "I=0x00"),
                                       ("s", "ls", "lsaddr", "ldfs", "I=0x01 & ls_LR=0")):
        for z in (0, 1, 2):
            for x in (0, 1):
                for wb in (0, 1, 2):   # no write-back, write-back to a register, .a on an immediate
                    sz = "^" + SZ[z] if z else ""
                    xd = '^".x"' if x else ""
                    ad = '^".a"' if wb else ""
                    wpat = {0: f"{fld}_A=0", 1: f"{fld}_A=1 & (Bb5=0 | (Bb5=1 & Bb4=0) | (Bb5=1 & Bb4=1 & Bb3=0) | Bt=14 | (Bt=15 & Bb1=0 & Bb0=0)) & B", 2: f"{fld}_A=1 & (Bt=15 & (Bb1=1 | (Bb1=0 & Bb0=1)))"}[wb]
                    A(f":ld{sz}^{fsuf}{xd}{ad}^{fld}di dst, {addr} is ({pfx} & {fld}_Z={z} & {fld}_X={x} & {fsuf} & {fld}di & dst & {wpat}) ... & {addr} ... {{")
                    A(f"\tlocal ea:4 = {addr};")
                    if wb == 1:
                        A("\tB = ea;")
                    A(f"\tdst = {LOADS[(z, x)]};")
                    A("}")
    STORES = {0: "*[ram]:4 ea = v;", 1: "*[ram]:1 ea = v:1;", 2: "*[ram]:2 ea = v:2;"}
    for z in (0, 1, 2):
        for wb in (0, 1, 2):
            sz = "^" + SZ[z] if z else ""
            ad = '^".a"' if wb else ""
            wpat = {0: "st_A=0", 1: "st_A=1 & (Bb5=0 | (Bb5=1 & Bb4=0) | (Bb5=1 & Bb4=1 & Bb3=0) | Bt=14 | (Bt=15 & Bb1=0 & Bb0=0)) & B", 2: "st_A=1 & (Bt=15 & (Bb1=1 | (Bb1=0 & Bb0=1)))"}[wb]
            A(f":st{sz}^ldfg{ad}^stdi stdata, lsaddr is (I=0x02 & st_SR=0 & st_Z={z} & ldfg & stdi & {wpat}) ... & stdata ... & lsaddr ... {{")
            A("\tlocal v:4 = stdata;\n\tlocal ea:4 = lsaddr;\n\t" + STORES[z])
            if wb == 1:
                A("\tB = ea;")
            A("}")
    A("")


generate()
open(sys.argv[1], "w").write("\n".join(out) + "\n")
